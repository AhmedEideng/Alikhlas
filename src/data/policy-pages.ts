/** الصفحة بالـ slug — تُستخدم في الواجهة وفي الـ prerender. */
export function getPolicyPage(slug: PolicyPage["slug"]): PolicyPage {
  const page = policyPages.find((entry) => entry.slug === slug);
  if (!page) throw new Error(`Unknown policy page: ${slug}`);
  return page;
}
