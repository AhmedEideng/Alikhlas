/**
 * الاسم القصير للقسم — يُستخدم في مسار التنقل (breadcrumb) في صفحة القسم
 * وفي صفحة كل منتج وفي HTML الزاحف، حتى لا يختلف الاسم بين ثلاثة أماكن.
 */
export function categoryBreadcrumbLabel(key: CategoryPageContent["key"]): string {
  return getCategoryPage(key).breadcrumbLabel;
}

export function getCategoryPage(key: CategoryPageContent["key"]): CategoryPageContent {
  const page = categoryPages.find((entry) => entry.key === key);
  if (!page) throw new Error(`Unknown category page: ${key}`);
  return page;
}
